            "from tqdm.auto import tqdm\n",
            "\n",
            "REQUIRED_KEYS = {\n",
            "    \"summary\", \"plain_explanation\", \"error_category\", \"likely_causes\",\n",
            "    \"missing_context_questions\", \"risk_level\", \"warnings\", \"repair_prompt\",\n",
            "    \"verification_steps\", \"matched_recipes\"\n",
            "}\n",
            "\n",
            "def run_audited_inference(model_inst, records, formatter_fn, desc, use_adapter):\n",
            "    model_inst.eval()\n",
            "    gen_cfg = CONFIG[\"generation\"]\n",
            "    outputs = []\n",
            "    \n",
            "    for r in tqdm(records, desc=desc):\n",
            "        prompt_msgs = [m for m in r[\"messages\"] if m[\"role\"] != \"assistant\"]\n",
            "        prompt_str = formatter_fn(prompt_msgs, tokenizer)\n",
            "        prompt_sha = hashlib.sha256(prompt_str.encode(\"utf-8\")).hexdigest()\n",
            "        \n",
            "        inputs = tokenizer(prompt_str, return_tensors=\"pt\").to(\"cuda\")\n",
            "        prompt_token_count = inputs[\"input_ids\"].shape[1]\n",
            "        \n",
            "        t0 = time.perf_counter()\n",
            "        with torch.no_grad():\n",
            "            if use_adapter:\n",
            "                model_inst.set_adapter(\"oopsie_pilot\")\n",
            "                out_ids = model_inst.generate(\n",
            "                    **inputs,\n",
            "                    max_new_tokens=gen_cfg[\"max_new_tokens\"],\n",
            "                    do_sample=gen_cfg[\"do_sample\"],\n",
            "                    pad_token_id=tokenizer.eos_token_id\n",
            "                )\n",
            "            else:\n",
            "                with model_inst.disable_adapter():\n",
            "                    out_ids = model_inst.generate(\n",
            "                        **inputs,\n",
            "                        max_new_tokens=gen_cfg[\"max_new_tokens\"],\n",
            "                        do_sample=gen_cfg[\"do_sample\"],\n",
            "                        pad_token_id=tokenizer.eos_token_id\n",
            "                    )\n",
            "        elapsed = time.perf_counter() - t0\n",
            "        \n",
            "        gen_tokens_tensor = out_ids[0][prompt_token_count:]\n",
            "        gen_tokens_list = gen_tokens_tensor.tolist()\n",
            "        gen_token_count = len(gen_tokens_list)\n",
            "        \n",
            "        eos_detected = (tokenizer.eos_token_id in gen_tokens_list)\n",
            "        hit_budget = (gen_token_count >= gen_cfg[\"max_new_tokens\"])\n",
            "        \n",
            "        raw_text = tokenizer.decode(gen_tokens_tensor, skip_special_tokens=True).strip()\n",
            "        raw_with_specials = tokenizer.decode(gen_tokens_tensor, skip_special_tokens=False)\n",
            "        \n",
            "        # Delimiter loop symptom detection: 3 or more repeated <|turn> tokens\n",
            "        turn_loop_detected = (raw_with_specials.count(\"<|turn>\") >= 3)\n",
            "        \n",
            "        # Schema validation\n",
            "        json_valid = False\n",
            "        schema_valid = False\n",
            "        parse_error = None\n",
            "        missing_keys = []\n",
            "        parsed = None\n",
            "        \n",
            "        clean_text = raw_text\n",
            "        if clean_text.startswith(\"```json\"):\n",
            "            clean_text = clean_text[7:]\n",
            "        if clean_text.endswith(\"```\"):\n",
            "            clean_text = clean_text[:-3]\n",
            "        clean_text = clean_text.strip()\n",
            "        \n",
            "        try:\n",
            "            parsed = json.loads(clean_text)\n",
            "            json_valid = True\n",
            "            if isinstance(parsed, dict):\n",
            "                missing_keys = list(REQUIRED_KEYS - parsed.keys())\n",
            "                schema_valid = (len(missing_keys) == 0)\n",
            "            else:\n",
            "                parse_error = \"Root JSON is not an object\"\n",
            "        except Exception as e:\n",
            "            parse_error = str(e)\n",
            "            \n",
            "        outputs.append({\n",
            "            \"id\": r[\"id\"],\n",
            "            \"prompt_sha256\": prompt_sha,\n",
            "            \"prompt_token_count\": prompt_token_count,\n",
            "            \"gen_token_count\": gen_token_count,\n",
            "            \"gen_token_ids\": gen_tokens_list,\n",
            "            \"eos_detected\": eos_detected,\n",
            "            \"hit_budget\": hit_budget,\n",
            "            \"turn_loop_detected\": turn_loop_detected,\n",
            "            \"elapsed_sec\": round(elapsed, 2),\n",
            "            \"json_valid\": json_valid,\n",
            "            \"schema_valid\": schema_valid,\n",
            "            \"parse_error\": parse_error,\n",
            "            \"missing_keys\": missing_keys,\n",
            "            \"raw_text\": raw_text,\n",
            "            \"raw_with_specials\": raw_with_specials,\n",
            "            \"parsed\": parsed\n",
            "        })\n",
            "    return outputs\n",
